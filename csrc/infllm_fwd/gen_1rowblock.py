"""Regenerate infllm_1rowblock.h: the OFFICIAL InfLLM-v2 forward row routine (compute_attn_1rowblock of
infllmv2_cuda_impl/csrc/flash_attn/src/flash_fwd_kernel.h, one warp = one token's 16 query heads of one KV head),
verbatim, renamed *_w, with three mechanical changes so that TWO independent warps of one CTA can each run it on their
own shared-memory slice: the shared-memory base is a parameter instead of the CTA's
`extern __shared__`; the thread index is the lane (threadIdx.x & 31); `__syncthreads()` becomes `__syncwarp()`
(the routine is single-warp: the CTA barrier only ever synchronised this warp with itself). In addition, when
params.o32_ptr is set, the normalised accumulator is stored in fp32 (and zero rows on the early exit) instead of the
fp16 store (bf16 with INFLLM_BF16). The compute is unchanged.
Run by build/build_ext.sh; the output is not checked in.
usage: python gen_1rowblock.py [official flash_fwd_kernel.h]"""
import os
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "third_party", "infllmv2_cuda_impl", "csrc", "flash_attn", "src", "flash_fwd_kernel.h")
L = open(src).read().split("\n")
i0 = next(i for i, l in enumerate(L) if l.startswith("inline __device__ void compute_attn_1rowblock(")) - 1
assert L[i0].startswith("template<typename Kernel_traits, bool Is_dropout, bool Is_causal, bool Is_local")
i1 = next(i for i, l in enumerate(L) if l.startswith("inline __device__ void compute_attn_1rowblock_splitkv(")) - 1
body = L[i0:i1]
while body and body[-1].strip() in ("", "/" * 100):
    body.pop()
assert body[-1] == "}", body[-3:]
s = "\n".join(body)
# (blockIdx appears only in the dropout branch, dead with Is_dropout = false, and in comments)
s = s.replace("inline __device__ void compute_attn_1rowblock(const Params &params, const int bidb, const int bidh, const int m_block) {",
              "inline __device__ void compute_attn_1rowblock_w(char *smem_, const Params &params, const int bidb, const int bidh, const int m_block) {   // [infllm_fwd] smem slice")
a = "    // Shared memory.\n    extern __shared__ char smem_[];\n"
assert a in s; s = s.replace(a, "    // [infllm_fwd] shared memory: the warp's slice, passed in\n")
a = "    const int tidx = threadIdx.x;\n"
assert s.count(a) == 1; s = s.replace(a, "    const int tidx = threadIdx.x & 31;              // [infllm_fwd] lane: one warp per row block\n")
# [infllm_fwd] fp32 partial O: when params.o32_ptr is set, the normalised accumulator is written in fp32 by the MMA C
# coordinates (row-major [total_q, h, d]) instead of the fp16 (bf16 with INFLLM_BF16) store; the LSE write is unchanged.
# The local / remote split merges two such partials in fp32 and rounds once.
o32_base = "reinterpret_cast<float *>(params.o32_ptr) + (binfo.q_offset((index_t)0, (index_t)1, bidb) + (index_t)m_block * kBlockM) * (params.h * kHeadDim) + bidh * kHeadDim"
a = """        flash::copy<Is_even_MN, Is_even_K, /*Clear_OOB_MN=*/false, /*Clear_OOB_K=*/false>(
            gmem_tiled_copy_O, tOrO, tOgO, tOcO, tOpO, binfo.actual_seqlen_q - m_block * kBlockM
        );
"""
assert s.count(a) == 1, s.count(a)              # the early-exit block (8-space indent)
s = s.replace(a, """        if (params.o32_ptr) {                       // [infllm_fwd] fp32 partial O: zero rows (empty part)
            float *o32 = """ + o32_base + """;
            for (int e = tidx; e < kBlockM * kHeadDim; e += 32) {
                const int r = e / kHeadDim, c = e - r * kHeadDim;
                if (r < binfo.actual_seqlen_q - m_block * kBlockM) o32[(int64_t)r * (params.h * kHeadDim) + c] = 0.f;
            }
        } else
""" + a)
a = "    Tensor cO = make_identity_tensor(make_shape(size<0>(sO), size<1>(sO)));"
assert s.count(a) == 1
s = s.replace(a, """    if (params.o32_ptr) {                           // [infllm_fwd] fp32 partial O by the MMA C coordinates
        float *o32 = """ + o32_base + """;
        #pragma unroll
        for (int i = 0; i < size(acc_o); ++i) {
            const int r = get<0>(taccOcO(i)), c = get<1>(taccOcO(i));
            if (r < binfo.actual_seqlen_q - m_block * kBlockM) o32[(int64_t)r * (params.h * kHeadDim) + c] = acc_o(i);
        }
        return;
    }
""" + a)
n_sync = s.count("__syncthreads()")
s = s.replace("__syncthreads()", "__syncwarp() /*[infllm_fwd] single-warp barrier*/")
code = "\n".join(l for l in s.split("\n") if not l.lstrip().startswith("//"))
assert "threadIdx" not in code.replace("threadIdx.x & 31", ""), "another threadIdx use"   # (comments excluded)
hdr = f"""#pragma once
// GENERATED by gen_1rowblock.py -- do not edit. The OFFICIAL InfLLM-v2 forward row routine (infllmv2_cuda_impl
// csrc/flash_attn/src/flash_fwd_kernel.h, compute_attn_1rowblock), verbatim, renamed *_w, with exactly the changes marked
// [infllm_fwd]: shared-memory base as a parameter, lane index, {n_sync} x __syncthreads -> __syncwarp (single-warp routine);
// and, when params.o32_ptr is set, the normalised accumulator is stored in fp32 (and zero rows on the early exit) instead
// of the fp16 store (bf16 with INFLLM_BF16).
// Include after the official headers, with the fork's `flash` namespace renamed (infllm_official.h).
namespace flash {{

"""
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "infllm_1rowblock.h")
open(out, "w").write(hdr + s + "\n\n}  // namespace flash\n")
print(out, s.count("\n"), "lines,", n_sync, "barriers, from", src)
